export function searchNumbers(query: string, group: NumberGroupId | "all" = "all") {
  const q = query.trim().toLowerCase();
  return USEFUL_NUMBERS.filter((item) => {
    if (group !== "all" && item.group !== group) return false;
    if (!q) return true;
    const label = NUMBER_GROUPS.find((g) => g.id === item.group);
    const hay = [item.value, item.titleHe, item.noteHe, label?.he, label?.en].join(" ").toLowerCase();
    return hay.includes(q);
  });
}
