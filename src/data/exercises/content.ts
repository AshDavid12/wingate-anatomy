export function toolLabel(id: ToolId) {
  const tool = TOOLS.find((item) => item.id === id);
  return tool ? tool.he : id;
}

export function matchesExercise(
  exercise: Exercise,
  query: { target?: string; role?: Role | "strengthen"; tool?: ToolId; kind?: Kind; chain?: Chain },
) {
  if (query.kind && exercise.kind !== query.kind) return false;
  if (query.chain && exercise.chain !== query.chain) return false;
  if (query.tool && !exercise.tools.includes(query.tool)) return false;
  if (!query.target) return true;
  if (!query.role || query.role === "strengthen") return exercise.targets.includes(query.target);
  const inAlso = exercise.also?.some((item) => item.target === query.target && item.role === query.role);
  if (query.role === "agonist") return exercise.targets.includes(query.target) || Boolean(inAlso);
  return Boolean(inAlso);
}

export function searchExercises(query: string, list: Exercise[] = EXERCISES) {
  const q = query.trim().toLowerCase();
  if (!q) return list;
  return list.filter((exercise) => {
    const targetText = exercise.targets
      .map((id) => TARGETS.find((target) => target.id === id))
      .flatMap((target) => (target ? [target.he, target.en, target.move] : []))
      .join(" ");
    const hay = [exercise.he, exercise.en, exercise.hook, targetText, ...(exercise.also?.map((item) => item.why) ?? [])]
      .join(" ")
      .toLowerCase();
    return hay.includes(q);
  });
}
