export function landmarksForBone(boneId: string): Landmark[] {
  return landmarks.filter((l) => l.boneId === boneId);
}

export function searchLandmarks(query: string, list: Landmark[] = landmarks): Landmark[] {
  const q = query.trim().toLowerCase();
  if (!q) return list;
  return list.filter((l) =>
    [l.nameHe, l.nameEn, l.locationHe, l.note ?? "", l.viewHe ?? "", l.boneId]
      .join(" ")
      .toLowerCase()
      .includes(q),
  );
}

export const examLandmarks = landmarks.filter((l) => l.exam);
